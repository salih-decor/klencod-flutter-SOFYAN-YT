def system_for(task: str, subject: str, mode: str) -> str:
    parts = [BASE_RULES, MODES.get(mode, MODES["model"]), TASKS.get(task, TASKS["exam"])]
    if subject in SUBJECT_GUIDES:
        parts.append(SUBJECT_GUIDES[subject])
    return "\n".join(parts)


def rag_context(sources: list[dict], passages: str, requested: bool) -> str:
    if sources:
        return RAG_WITH.format(passages=passages)
    return RAG_NONE if requested else ""
